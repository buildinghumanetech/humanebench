#!/usr/bin/env python3
"""Copy rubrics/judge_prompt_v4.md into the standalone evaluators, byte for byte.

The evaluators are meant to be copied, one file at a time, into other codebases,
so each one carries its own copy of the judge prompt instead of reading
``../rubrics/judge_prompt_v4.md`` at runtime. A vendored copy is how two prompts
drift apart, so this script is the only thing that should ever write that copy,
and ``--check`` (run by the test suites) fails when any copy differs from the
source.

Usage:
    python sync_judge_prompt.py          # rewrite the embedded copies
    python sync_judge_prompt.py --check  # exit 1 if any copy has drifted

The TypeScript evaluator is the source of the JavaScript one (``npm run build``).
This script writes the prompt line in both, so a sync does not require a rebuild,
but rebuild after any other change to the TypeScript.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "rubrics" / "judge_prompt_v4.md"

BEGIN = "BEGIN judge_prompt_v4.md (generated by sync_judge_prompt.py; do not edit by hand)"
END = "END judge_prompt_v4.md"

# (file, comment prefix, declaration keyword)
TARGETS = [
    (HERE / "humanebench_evaluator.py", "#", ""),
    (HERE / "humanebench_evaluator.ts", "//", "const "),
    (HERE / "humanebench_evaluator.js", "//", "var "),
]


def read_source() -> str:
    # newline="" keeps the bytes exactly as committed: no newline translation.
    with SOURCE.open(encoding="utf-8", newline="") as f:
        return f.read()


def python_literal(text: str) -> str:
    # A plain triple-quoted string keeps the prompt readable in the file. It is
    # only byte-exact when the text has no backslash and no triple quote, so fall
    # back to a JSON literal (also valid Python) if the prompt ever gains one.
    if "\\" in text or '"""' in text or text.endswith('"'):
        return json.dumps(text, ensure_ascii=False)
    return '"""' + text + '"""'


def js_literal(text: str) -> str:
    # One JSON string literal: valid TypeScript and JavaScript, and tsc emits it
    # verbatim, so the compiled .js carries the identical line.
    return json.dumps(text, ensure_ascii=False)


def render_block(path: Path, prefix: str, keyword: str, text: str) -> str:
    literal = python_literal(text) if path.suffix == ".py" else js_literal(text)
    semicolon = "" if path.suffix == ".py" else ";"
    return (
        f"{prefix} {BEGIN}\n"
        f"{keyword}HUMANEBENCH_TEMPLATE = {literal}{semicolon}\n"
        f"{prefix} {END}\n"
    )


def block_pattern(prefix: str) -> re.Pattern:
    return re.compile(
        rf"^{re.escape(prefix)} {re.escape(BEGIN)}\n.*?^{re.escape(prefix)} {re.escape(END)}\n",
        re.DOTALL | re.MULTILINE,
    )


def check_or_write(write: bool) -> list[str]:
    text = read_source()
    problems: list[str] = []
    for path, prefix, keyword in TARGETS:
        with path.open(encoding="utf-8", newline="") as f:
            current = f.read()
        matches = list(block_pattern(prefix).finditer(current))
        if len(matches) != 1:
            problems.append(f"{path.name}: expected one embedded prompt block, found {len(matches)}")
            continue
        wanted = render_block(path, prefix, keyword, text)
        if matches[0].group(0) == wanted:
            continue
        if write:
            m = matches[0]
            updated = current[: m.start()] + wanted + current[m.end():]
            with path.open("w", encoding="utf-8", newline="") as f:
                f.write(updated)
            print(f"updated {path.name}")
        else:
            problems.append(f"{path.name}: embedded prompt differs from {SOURCE.relative_to(HERE.parent)}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Fail if any embedded copy has drifted; write nothing")
    args = parser.parse_args()
    problems = check_or_write(write=not args.check)
    for p in problems:
        print(p, file=sys.stderr)
    if problems:
        if args.check:
            print("Run: python evaluator/sync_judge_prompt.py", file=sys.stderr)
        return 1
    if args.check:
        print("embedded judge prompts match rubrics/judge_prompt_v4.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
