//! Claude Code session logs: a tree linked through `parentUuid`.
//!
//! Field names here were read off real session transcripts. Most record types in a
//! Claude Code log are not conversation at all — see `DROP_TYPES`.

use crate::transcript::{Action, Record, Role, SCHEMA};
use anyhow::Result;
use chrono::{DateTime, Utc};
use serde_json::Value;
use std::collections::HashMap;

pub const SOURCE: &str = "claude-code";

/// Prefixes that mark a `user` record as something the harness generated rather than
/// something a person typed.
///
/// Enumerated against a real corpus of 393 session files rather than guessed. Observed
/// there: `<local-command-caveat>`, `<local-command-stdout>`, `<command-name>`,
/// `<task-notification>`, `[Request interrupted`, and the compaction continuation. The
/// remainder are siblings of those same envelopes — `<command-message>`/`<command-args>`
/// ride in the same block as `<command-name>`, `<local-command-stderr>` in the same block
/// as its stdout twin — plus the two injections Claude Code is documented to prepend.
/// Every one of these was reaching the judge verbatim, scored as if the human wrote it.
const HARNESS_PREFIXES: &[&str] = &[
    "<local-command-caveat",
    "<local-command-stdout",
    "<local-command-stderr",
    "<command-name",
    "<command-message",
    "<command-args",
    "<task-notification",
    "<system-reminder",
    "<user-prompt-submit-hook",
    "[Request interrupted",
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",
];

/// Record types that are harness bookkeeping, not conversation.
const DROP_TYPES: &[&str] = &[
    "attachment",
    "file-history-delta",
    "file-history-snapshot",
    "ai-title",
    "mode",
    "permission-mode",
    "queue-operation",
    "bridge-session",
    "last-prompt",
    "system",
];

/// Recognize a Claude Code log from its first parseable record.
pub fn detect(sample: &str) -> bool {
    for line in sample.lines().take(50) {
        let Ok(v) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        if v.get("parentUuid").is_some() || v.get("isSidechain").is_some() {
            return true;
        }
        if v.get("uuid").is_some() && v.get("sessionId").is_some() {
            return true;
        }
    }
    false
}

/// Pull a short, human-legible summary out of a tool_use `input` object.
fn summarize_tool(name: &str, input: &Value) -> String {
    let pick = |k: &str| input.get(k).and_then(|v| v.as_str()).map(str::to_string);

    let raw = match name {
        "Bash" => pick("command"),
        "Read" | "Edit" | "Write" | "NotebookEdit" => pick("file_path"),
        "Grep" | "Glob" => pick("pattern"),
        "Task" | "Agent" => pick("description"),
        "WebFetch" => pick("url"),
        "ToolSearch" => pick("query"),
        _ => None,
    }
    .or_else(|| {
        // Fall back to the first short string field, so unknown tools still say something.
        input.as_object().and_then(|o| {
            o.values()
                .find_map(|v| v.as_str().filter(|s| !s.is_empty()))
                .map(str::to_string)
        })
    })
    .unwrap_or_default();

    let one_line = raw.split_whitespace().collect::<Vec<_>>().join(" ");
    truncate(&one_line, 120)
}

fn truncate(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        return s.to_string();
    }
    let mut out: String = s.chars().take(max).collect();
    out.push('…');
    out
}

/// Concatenate the `text` blocks of a content value. `thinking` and `tool_use` blocks are
/// deliberately excluded: the former is not the response, the latter is context.
fn text_blocks(content: &Value) -> String {
    match content {
        Value::String(s) => s.clone(),
        Value::Array(blocks) => {
            let mut buf = String::new();
            for b in blocks {
                if b.get("type").and_then(|t| t.as_str()) == Some("text") {
                    if let Some(t) = b.get("text").and_then(|t| t.as_str()) {
                        if !buf.is_empty() {
                            buf.push('\n');
                        }
                        buf.push_str(t);
                    }
                }
            }
            buf
        }
        _ => String::new(),
    }
}

/// True when a user record's text is a harness envelope rather than a typed prompt.
fn is_harness_envelope(trimmed: &str) -> bool {
    HARNESS_PREFIXES.iter().any(|p| trimmed.starts_with(p))
}

/// Read a boolean marker off a record, defaulting to false when absent or the wrong type.
fn flag(v: &Value, key: &str) -> bool {
    v.get(key).and_then(|b| b.as_bool()).unwrap_or(false)
}

pub fn parse(input: &str) -> Result<Vec<Record>> {
    let mut out: Vec<Record> = Vec::new();
    // tool_use blocks seen since the last text-bearing assistant turn.
    let mut pending: Vec<Action> = Vec::new();
    // Every uuid -> parentUuid link in the file, kept and dropped alike.
    let mut parent_of: HashMap<String, Option<String>> = HashMap::new();

    for line in input.lines() {
        if line.trim().is_empty() {
            continue;
        }
        let Ok(v) = serde_json::from_str::<Value>(line) else {
            continue; // a corrupt line in a log is not a reason to abort the file
        };

        // Record the link before any filtering: dropped records are still chain links.
        if let Some(uuid) = v.get("uuid").and_then(|u| u.as_str()) {
            parent_of.insert(
                uuid.to_string(),
                v.get("parentUuid")
                    .and_then(|p| p.as_str())
                    .map(str::to_string),
            );
        }

        let rtype = v.get("type").and_then(|t| t.as_str()).unwrap_or("");
        if DROP_TYPES.contains(&rtype) {
            continue;
        }
        if rtype != "user" && rtype != "assistant" {
            continue;
        }

        let message = v.get("message").cloned().unwrap_or(Value::Null);
        let content = message.get("content").cloned().unwrap_or(Value::Null);

        // Collect tool_use blocks regardless of whether this record carries text.
        if rtype == "assistant" {
            if let Some(blocks) = content.as_array() {
                for b in blocks {
                    if b.get("type").and_then(|t| t.as_str()) == Some("tool_use") {
                        let name = b
                            .get("name")
                            .and_then(|n| n.as_str())
                            .unwrap_or("tool")
                            .to_string();
                        let summary = b
                            .get("input")
                            .map(|i| summarize_tool(&name, i))
                            .unwrap_or_default();
                        pending.push(Action { name, summary });
                    }
                }
            }
        }

        // Harness bookkeeping wearing a user record's clothes. `isMeta` marks injected
        // context — auto-resume nudges, Stop-hook feedback, the skill preamble that
        // carries a whole SKILL.md body — and `isCompactSummary` marks a summary the
        // model wrote about itself. Neither is a person talking. Scoring them charges the
        // harness's words to the human, and ships their contents off the machine.
        if flag(&v, "isMeta") || flag(&v, "isCompactSummary") {
            continue;
        }

        // A user record carrying only `tool_result` blocks is the harness replying to
        // itself and falls out here with empty text. One carrying BOTH a tool_result and
        // typed text is a person typing while a tool ran: `text_blocks` keeps what they
        // typed and ignores the rest, so the record survives. Dropping it wholesale left
        // the NEXT assistant turn paired with a stale prompt — a silently wrong score
        // rather than a missing one.
        let text = text_blocks(&content);
        let trimmed = text.trim();
        if trimmed.is_empty() {
            continue;
        }
        if rtype == "user" && is_harness_envelope(trimmed) {
            continue;
        }

        let Some(ts) = v.get("timestamp").and_then(|t| t.as_str()) else {
            continue;
        };
        let Ok(timestamp) = DateTime::parse_from_rfc3339(ts).map(|t| t.with_timezone(&Utc)) else {
            continue;
        };

        let Some(uuid) = v.get("uuid").and_then(|u| u.as_str()) else {
            continue;
        };
        let session_id = v
            .get("sessionId")
            .and_then(|s| s.as_str())
            .unwrap_or("unknown")
            .to_string();

        let role = if rtype == "user" {
            Role::User
        } else {
            Role::Assistant
        };

        let mut rec = Record {
            schema: SCHEMA.to_string(),
            source: SOURCE.to_string(),
            session_id,
            turn_id: uuid.to_string(),
            role,
            text: trimmed.to_string(),
            timestamp,
            // uuid/parentUuid map straight on, which is why Claude Code needs no id synthesis.
            parent_id: v
                .get("parentUuid")
                .and_then(|p| p.as_str())
                .map(str::to_string),
            model: message
                .get("model")
                .and_then(|m| m.as_str())
                .map(str::to_string),
            actions: Vec::new(),
            sidechain: v
                .get("isSidechain")
                .and_then(|s| s.as_bool())
                .unwrap_or(false),
        };

        if role == Role::Assistant {
            rec.actions = std::mem::take(&mut pending);
        }

        out.push(rec);
    }

    // Re-link across everything that was dropped, so the tree stays walkable.
    crate::transcript::relink_to_kept_ancestors(&mut out, &parent_of);

    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    const REAL_SHAPE: &str = r#"
{"type":"queue-operation","uuid":"q1","timestamp":"2026-07-30T16:40:00.000Z"}
{"type":"user","uuid":"u1","parentUuid":null,"sessionId":"df03642d","timestamp":"2026-07-30T16:41:00.000Z","isSidechain":false,"message":{"content":"why is the upload flaky?"}}
{"type":"assistant","uuid":"a1","parentUuid":"u1","sessionId":"df03642d","timestamp":"2026-07-30T16:41:30.000Z","isSidechain":false,"message":{"model":"claude-opus-5","content":[{"type":"tool_use","id":"t1","name":"Bash","input":{"command":"git status"}},{"type":"tool_use","id":"t2","name":"Read","input":{"file_path":"src/app.ts"}}]}}
{"type":"user","uuid":"u2","parentUuid":"a1","sessionId":"df03642d","timestamp":"2026-07-30T16:41:40.000Z","isSidechain":false,"message":{"content":[{"type":"tool_result","tool_use_id":"t1","content":"clean"}]}}
{"type":"assistant","uuid":"a2","parentUuid":"u2","sessionId":"df03642d","timestamp":"2026-07-30T16:42:07.833Z","isSidechain":false,"message":{"model":"claude-opus-5","content":[{"type":"text","text":"The xhigh review …"}]}}
{"type":"attachment","uuid":"x1","timestamp":"2026-07-30T16:43:00.000Z"}
{"type":"last-prompt","uuid":"x2","timestamp":"2026-07-30T16:43:01.000Z"}
"#;

    #[test]
    fn detects_claude_code() {
        assert!(detect(REAL_SHAPE));
    }

    #[test]
    fn keeps_only_conversation_records() {
        let recs = parse(REAL_SHAPE).unwrap();
        let ids: Vec<&str> = recs.iter().map(|r| r.turn_id.as_str()).collect();
        // q1/x1/x2 dropped by type; u2 dropped as a tool_result; a1 has no text.
        assert_eq!(ids, vec!["u1", "a2"]);
    }

    #[test]
    fn folds_tool_uses_into_the_next_text_turn() {
        let recs = parse(REAL_SHAPE).unwrap();
        let a2 = recs.iter().find(|r| r.turn_id == "a2").unwrap();
        assert_eq!(a2.actions.len(), 2);
        assert_eq!(a2.actions[0].name, "Bash");
        assert_eq!(a2.actions[0].summary, "git status");
        assert_eq!(a2.actions[1].name, "Read");
        assert_eq!(a2.actions[1].summary, "src/app.ts");
    }

    #[test]
    fn maps_ids_and_model_straight_through() {
        let recs = parse(REAL_SHAPE).unwrap();
        let a2 = recs.iter().find(|r| r.turn_id == "a2").unwrap();
        assert_eq!(a2.model.as_deref(), Some("claude-opus-5"));
        assert_eq!(a2.session_id, "df03642d");
        assert!(!a2.sidechain);
    }

    /// Regression, found against a real session: the chain a2 -> u2 -> a1 -> u1 passes
    /// through two dropped records. Leaving parent_id pointing at the dropped u2 orphans
    /// the tree, and the newest-leaf walk then keeps a single record and discards the
    /// whole conversation.
    #[test]
    fn relinks_across_dropped_records() {
        let recs = parse(REAL_SHAPE).unwrap();
        let a2 = recs.iter().find(|r| r.turn_id == "a2").unwrap();
        assert_eq!(
            a2.parent_id.as_deref(),
            Some("u1"),
            "must re-link to the nearest KEPT ancestor, not the dropped tool_result"
        );

        // And the whole conversation must survive flattening.
        let (kept, discarded) = crate::transcript::flatten(recs);
        assert_eq!(kept.len(), 2, "flatten dropped the conversation");
        assert_eq!(discarded, 0);
    }

    #[test]
    fn root_record_keeps_a_null_parent() {
        let recs = parse(REAL_SHAPE).unwrap();
        let u1 = recs.iter().find(|r| r.turn_id == "u1").unwrap();
        assert!(u1.parent_id.is_none());
    }

    #[test]
    fn drops_local_command_caveat_records() {
        let input = r#"{"type":"user","uuid":"u9","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"<local-command-caveat>ran /clear</local-command-caveat>"}}"#;
        assert!(parse(input).unwrap().is_empty());
    }

    /// F6 regression. Each of these was reaching the judge verbatim, scored as if the
    /// person had typed it. On a real 393-file corpus they were 243 of 2005 kept user
    /// turns (12%).
    #[test]
    fn drops_harness_generated_user_records() {
        let cases: &[(&str, &str)] = &[
            (
                "isMeta auto-resume nudge",
                r#"{"type":"user","uuid":"m1","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","isMeta":true,"message":{"content":"Continue from where you left off."}}"#,
            ),
            (
                "isMeta Stop-hook feedback",
                r#"{"type":"user","uuid":"m2","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","isMeta":true,"message":{"content":"Stop hook feedback:\nconcierge — 1 message(s) queued for you"}}"#,
            ),
            (
                "isMeta skill injection carrying a SKILL.md body",
                r#"{"type":"user","uuid":"m3","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","isMeta":true,"message":{"content":"Base directory for this skill: /tmp/skills/x\n\n# Some Skill\n\nWhole body here."}}"#,
            ),
            (
                "isCompactSummary",
                r#"{"type":"user","uuid":"m4","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","isCompactSummary":true,"message":{"content":"This session is being continued from a previous conversation that ran out of context.\n\nSummary:\n1. Primary Request…"}}"#,
            ),
            (
                "/compact slash-command envelope",
                r#"{"type":"user","uuid":"m5","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"<command-name>/compact</command-name>\n<command-message>compact</command-message>\n<command-args></command-args>"}}"#,
            ),
            (
                "slash-command stdout",
                r#"{"type":"user","uuid":"m6","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"<local-command-stdout>Set model to Sonnet 5</local-command-stdout>"}}"#,
            ),
            (
                "background task notification",
                r#"{"type":"user","uuid":"m7","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"<task-notification>\n<task-id>abc</task-id>\n<status>done</status>\n</task-notification>"}}"#,
            ),
            (
                "interrupt marker",
                r#"{"type":"user","uuid":"m8","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"[Request interrupted by user for tool use]"}}"#,
            ),
            (
                "injected system reminder",
                r#"{"type":"user","uuid":"m9","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"<system-reminder>Background context, not a prompt.</system-reminder>"}}"#,
            ),
            (
                "compaction continuation without the flag",
                r#"{"type":"user","uuid":"m10","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"This session is being continued from a previous conversation that ran out of context."}}"#,
            ),
        ];

        for (label, line) in cases {
            let recs = parse(line).unwrap();
            assert!(
                recs.is_empty(),
                "{label} must not be scored as a user prompt; got {:?}",
                recs.iter().map(|r| &r.text).collect::<Vec<_>>()
            );
        }
    }

    /// A human prompt that merely mentions one of the envelopes must survive — the filter
    /// keys on the record leading with it, not containing it.
    #[test]
    fn keeps_a_human_prompt_that_only_mentions_an_envelope() {
        let line = r#"{"type":"user","uuid":"h1","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":"why does <system-reminder> keep showing up in my logs?"}}"#;
        let recs = parse(line).unwrap();
        assert_eq!(recs.len(), 1);
    }

    /// F7 regression. A user record carrying BOTH a tool_result and typed text is a person
    /// typing while a tool ran. Dropping it wholesale left the next assistant turn paired
    /// with the previous prompt — a wrong score, not a missing one.
    #[test]
    fn mixed_tool_result_and_typed_text_keeps_the_typed_text() {
        const MIXED: &str = r#"
{"type":"user","uuid":"u1","parentUuid":null,"sessionId":"s","timestamp":"2026-07-30T16:40:00.000Z","message":{"content":"find the flaky test"}}
{"type":"assistant","uuid":"a1","parentUuid":"u1","sessionId":"s","timestamp":"2026-07-30T16:40:10.000Z","message":{"model":"m","content":[{"type":"tool_use","id":"t1","name":"Bash","input":{"command":"cargo test"}}]}}
{"type":"user","uuid":"u2","parentUuid":"a1","sessionId":"s","timestamp":"2026-07-30T16:40:20.000Z","message":{"content":[{"type":"tool_result","tool_use_id":"t1","content":"1 failed"},{"type":"text","text":"actually stop, just tell me which file it lives in"}]}}
{"type":"assistant","uuid":"a2","parentUuid":"u2","sessionId":"s","timestamp":"2026-07-30T16:40:30.000Z","message":{"model":"m","content":[{"type":"text","text":"tests/flaky.rs"}]}}
"#;
        let recs = parse(MIXED).unwrap();
        let u2 = recs
            .iter()
            .find(|r| r.turn_id == "u2")
            .expect("the typed half of a mixed record must survive");
        assert_eq!(
            u2.text,
            "actually stop, just tell me which file it lives in"
        );
        assert_eq!(u2.role, Role::User);
        assert!(
            !u2.text.contains("1 failed"),
            "the tool_result portion must not be carried into the prompt"
        );

        // And the next assistant turn must be judged against that prompt, not the earlier one.
        let sessions =
            crate::transcript::sessionize(recs, crate::transcript::DEFAULT_IDLE_GAP_HOURS);
        let turns = crate::transcript::scorable_turns(&sessions[0]);
        let a2 = turns
            .iter()
            .find(|t| t.turn_id == "a2")
            .expect("a2 must be scorable");
        assert_eq!(
            a2.user_prompt, "actually stop, just tell me which file it lives in",
            "a2 answered the typed text, not the prompt before it"
        );
    }

    /// The other half of F7: a user record that is ONLY tool_result stays dropped.
    #[test]
    fn tool_result_only_records_are_still_dropped() {
        let line = r#"{"type":"user","uuid":"u2","sessionId":"s","timestamp":"2026-07-30T16:41:00.000Z","message":{"content":[{"type":"tool_result","tool_use_id":"t1","content":"clean"}]}}"#;
        assert!(parse(line).unwrap().is_empty());
    }

    #[test]
    fn skips_corrupt_lines_without_aborting() {
        let input = format!("{{not json\n{}", REAL_SHAPE);
        assert_eq!(parse(&input).unwrap().len(), 2);
    }
}
